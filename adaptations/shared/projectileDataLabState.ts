const projectileTypes = [ CANNONBALL, PUMPKIN, PIANO ];
const mechanisms = [
  LauncherMechanism.SPRING, LauncherMechanism.PRESSURE, LauncherMechanism.EXPLOSION,
  LauncherMechanism.CUSTOM_MECHANISM_1, LauncherMechanism.CUSTOM_MECHANISM_2, LauncherMechanism.CUSTOM_MECHANISM_3
];

function reference<T extends { phetioID: string }>( property: Property<T>, choices: readonly T[] ) {
  return field( property, value => value.phetioID, value => choices.find( item => item.phetioID === value ) );
}

function readProjectile( projectile: Projectile ) {
  return {
    sample: projectile.sampleNumber,
    orientation: projectile.launcherOrientation,
    launcher: projectile.launcher.phetioID,
    mechanism: projectile.launcherMechanism.phetioID,
    angleDeviation: projectile.launcherStandardDeviationAngle,
    x: projectile.x,
    y: projectile.y,
    type: projectile.type.phetioID,
    flipped: projectile.isFlippedHorizontally,
    image: projectile.landedImageIndex,
    time: projectile.timeAirborne,
    angle: projectile.launchAngle,
    speed: projectile.launchSpeed,
    height: projectile.launchHeight
  };
}

function finite( value: unknown, min = -Infinity ): number {
  if ( typeof value !== 'number' || !Number.isFinite( value ) || value < min ) {
    throw new Error( 'Invalid Projectile Data Lab number.' );
  }
  return value;
}

function projectile( owner: Field, id: ScreenIdentifier, input: unknown ): Projectile {
  const state = object( input );
  const orientation = LauncherOrientationValues.find( item => item === state.orientation );
  const launcher = owner.launchers.find( item => item.phetioID === state.launcher );
  const mechanism = mechanisms.find( item => item.phetioID === state.mechanism );
  const type = projectileTypes.find( item => item.phetioID === state.type );
  const sample = finite( state.sample, 1 );
  const image = finite( state.image, 0 );
  const maxSample = owner instanceof SamplingField ? QueryParameters.maxSamples : 1;
  if ( !orientation || !launcher || !mechanism || !type || typeof state.flipped !== 'boolean' ||
       !Number.isInteger( sample ) || sample > maxSample || !Number.isInteger( image ) || image > 2 ) {
    throw new Error( 'Invalid Projectile Data Lab projectile.' );
  }
  return new Projectile( id, owner[ 'identifier' ], sample, orientation, launcher, mechanism,
    finite( state.angleDeviation, 0 ), finite( state.x ), finite( state.y ), type, state.flipped, image,
    finite( state.time, 0 ), finite( state.angle ), finite( state.speed ), finite( state.height, 0 ) );
}

function fieldState( owner: SamplingField | VSMField, id: ScreenIdentifier ) {
  const controls: Parameters<typeof readFields>[ 0 ] = {
    orientation: enumeration( owner.launcherOrientationProperty ),
    projectileType: reference( owner.projectileTypeProperty, owner.projectileTypeProperty.validValues ?? projectileTypes ),
    continuous: boolean( owner.isContinuousLaunchingProperty )
  };
  const phase: Parameters<typeof readFields>[ 0 ] = {};
  const launcherControls = ( launcher: Launcher ) => ( {
    mechanism: reference( launcher.launcherMechanismProperty, mechanisms ),
    stability: number( launcher.angleStabilityProperty )
  } );
  let launchers: ReturnType<typeof launcherControls>[] = [];
  if ( owner instanceof SamplingField ) {
    phase.selectedSample = number( owner.selectedSampleNumberProperty, true );
    phase.phase = enumeration( owner.phaseProperty );
    phase.time = number( owner[ 'timeProperty' ], false, value => value >= 0 );
    phase.phaseStart = number( owner[ 'phaseStartTimeProperty' ], false, value => value >= 0 );
  }
  else {
    if ( owner instanceof MeasuresField ) {
      controls.launcherMode = enumeration( owner.mysteryOrCustomProperty );
      controls.mysteryLauncher = reference( owner.mysteryLauncherProperty, owner.launchers );
    }
    else {
      controls.launcher = reference( owner.launcherProperty, owner.launchers );
    }
    launchers = owner.launchers.map( launcherControls );
    phase.selectedProjectile = number( owner.selectedProjectileNumberProperty, true );
    phase.latestLaunchAngle = number( owner.latestLaunchAngleProperty );
    phase.latestLaunchSpeed = number( owner.latestLaunchSpeedProperty );
    phase.timerRunning = boolean( owner.continuousLaunchTimer[ 'isRunningProperty' ] );
    phase.timerRemaining = number( owner.continuousLaunchTimer[ 'timeRemainingProperty' ] );
  }
  return {
    read: () => ( {
      controls: readFields( controls ),
      phase: readFields( phase ),
      launchers: launchers.map( readFields ),
      airborne: owner.airborneProjectiles.map( readProjectile ),
      landed: owner.landedProjectiles.map( readProjectile )
    } ),
    prepare: ( input: unknown ) => {
      const state = object( input );
      const phaseState = object( state.phase );
      const max = owner instanceof SamplingField ? QueryParameters.maxSamples * owner.sampleSize : QueryParameters.maxProjectilesVSMField;
      if ( !Array.isArray( state.airborne ) || !Array.isArray( state.landed ) ||
           state.airborne.length + state.landed.length > max ||
           !Array.isArray( state.launchers ) || state.launchers.length !== launchers.length ) {
        throw new Error( 'Invalid Projectile Data Lab field.' );
      }
      const airborne = state.airborne.map( item => projectile( owner, id, item ) );
      const landed = state.landed.map( item => projectile( owner, id, item ) );
      if ( landed.some( item => item.y !== 0 ) ||
           ( owner instanceof VSMField && Number( phaseState.selectedProjectile ) > landed.length ) ||
           ( owner instanceof SamplingField && Number( phaseState.phaseStart ) > Number( phaseState.time ) ) ) {
        throw new Error( 'Invalid Projectile Data Lab data selection.' );
      }
      const applyControls = prepareFields( controls, state.controls );
      const applyLaunchers = state.launchers.map( ( input, index ) => prepareFields( launchers[ index ], input ) );
      const applyPhase = prepareFields( phase, phaseState );
      return () => {
        owner.clearProjectiles();
        applyLaunchers.forEach( apply => apply() );
        applyControls();
        airborne.forEach( item => owner.airborneProjectiles.push( item ) );
        landed.forEach( item => owner.landedProjectiles.push( item ) );
        owner.isContainingDataProperty.value = landed.length > 0;
        if ( owner instanceof VSMField ) { owner[ 'updateProjectileCounts' ](); }
        applyPhase();
        if ( owner instanceof SamplingField ) { owner.updateComputedProperties(); }
        if ( owner instanceof MeasuresField ) {
          const deviation = owner[ 'getStandardDeviationDistance' ]();
          owner.meanDistanceProperty.value = landed.length ? landed.reduce( ( sum, item ) => sum + item.x, 0 ) / landed.length : null;
          owner.standardDeviationDistanceProperty.value = deviation;
          owner.standardErrorDistanceProperty.value = deviation === null ? null : deviation / Math.sqrt( landed.length );
        }
        owner.projectilesChangedEmitter.emit();
      };
    }
  };
}

export function projectileDataLabScreenState( screen: AnyScreen, id: ScreenIdentifier ) {
  const model = screen.model as SamplingModel | VSMModel<VSMField>;
  const view = screen.view as PDLScreenView<SamplingField | VSMField>;
  const controls: Parameters<typeof readFields>[ 0 ] = {
    playing: boolean( model.isPlayingProperty ),
    speed: enumeration( model.timeSpeedProperty ),
    paths: boolean( model.isPathsVisibleProperty ),
    launchMode: enumeration( model.singleOrContinuousProperty ),
    histogramZoom: number( model.histogram.zoomProperty ),
    histogramBinWidth: enumeration( model.histogram.selectedBinWidthProperty ),
    histogramTotalBins: enumeration( model.histogram.selectedTotalBinsProperty ),
    histogramStyle: enumeration( model.histogram.representationProperty ),
    histogramExpanded: boolean( view[ 'accordionBox' ].expandedProperty )
  };
  if ( model instanceof SamplingModel ) {
    controls.launcher = reference( model.launcherProperty, model.launcherProperty.validValues! );
    controls.sampleSize = enumeration( model.sampleSizeProperty );
  }
  else {
    controls.field = reference( model.fieldProperty, model.fields );
    controls.showAngle = boolean( model.isLaunchAngleVisibleProperty );
    controls.showSpeed = boolean( model.isLaunchSpeedVisibleProperty );
    controls.tapeVisible = boolean( model.isMeasuringTapeVisibleProperty );
    controls.tapeBase = vector( model.measuringTapeBasePositionProperty );
    controls.tapeTip = vector( model.measuringTapeTipPositionProperty );
    controls.stopwatchPosition = vector( model.stopwatch.positionProperty );
    controls.stopwatchVisible = boolean( model.stopwatch.isVisibleProperty );
    controls.stopwatchRunning = boolean( model.stopwatch.isRunningProperty );
    controls.stopwatchTime = number( model.stopwatch.timeProperty, false, value => value >= 0 );
  }
  if ( model instanceof MeasuresModel ) {
    controls.showMean = boolean( model.isMeanVisibleProperty );
    controls.showDeviation = boolean( model.isStandardDeviationVisibleProperty );
    controls.showValues = boolean( model.isValuesVisibleProperty );
    controls.intervalVisible = boolean( model.isIntervalToolVisibleProperty );
    controls.intervalStart = number( model.intervalTool.edge1Property );
    controls.intervalEnd = number( model.intervalTool.edge2Property );
  }
  const fields = model.fields.map( item => fieldState( item, id ) );
  const mechanismSettings = mechanisms.map( item => ( {
    speed: number( item.speedMeanProperty ),
    speedDeviation: number( item.speedStandardDeviationProperty )
  } ) );
  return {
    id, screen,
    isPlaying: () => {
      const current = model.fieldProperty.value;
      return model.isPlayingProperty.value && ( current.isContinuousLaunchingProperty.value ||
        current.airborneProjectiles.length > 0 || ( current instanceof SamplingField ?
          current.phaseProperty.value === 'showingCompleteSampleWithoutMean' : ( model as VSMModel<VSMField> ).stopwatch.isRunningProperty.value ) );
    },
    read: () => ( {
      controls: readFields( controls ),
      fields: fields.map( item => item.read() ),
      mechanisms: mechanismSettings.map( readFields )
    } ),
    prepare: ( input: unknown ) => {
      const state = object( input );
      if ( !Array.isArray( state.fields ) || state.fields.length !== fields.length ||
           !Array.isArray( state.mechanisms ) || state.mechanisms.length !== mechanisms.length ) {
        throw new Error( 'Invalid Projectile Data Lab screen.' );
      }
      const restoreControls = prepareFields( controls, state.controls );
      const restoreFields = state.fields.map( ( item, index ) => fields[ index ].prepare( item ) );
      const restoreMechanisms = state.mechanisms.map( ( item, index ) => prepareFields( mechanismSettings[ index ], item ) );
      return () => {
        screen.view.interruptSubtreeInput();
        isSettingPhetioStateProperty.value = true;
        try {
          model.fields.forEach( item => item.clearProjectiles() );
          restoreMechanisms.forEach( apply => apply() );
          restoreControls();
          restoreFields.forEach( apply => apply() );
          if ( model instanceof MeasuresModel ) {
            const min = Math.min( model.intervalTool.edge1Property.value, model.intervalTool.edge2Property.value );
            const max = Math.max( model.intervalTool.edge1Property.value, model.intervalTool.edge2Property.value );
            const landed = model.fieldProperty.value.landedProjectiles;
            model.intervalTool.dataFractionProperty.value = landed.length ?
              landed.filter( item => item.x >= min && item.x <= max ).length / landed.length : 0;
          }
        }
        finally { isSettingPhetioStateProperty.value = false; }
      };
    }
  };
}

export function samplingState( screen: SamplingScreen ) {
  return projectileDataLabScreenState( screen, 'sampling' );
}
